CREATE TABLE venues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    city VARCHAR(100) NOT NULL,
    address VARCHAR(300) NOT NULL
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

-- Nullable: mevcut etkinlikler ve events.venue sütunu olduğu gibi çalışmaya devam eder.
ALTER TABLE events ADD COLUMN venue_id BIGINT REFERENCES venues(id);
ALTER TABLE events ADD COLUMN category_id BIGINT REFERENCES categories(id);

CREATE INDEX idx_events_venue ON events(venue_id);
CREATE INDEX idx_events_category ON events(category_id);

