-- Upgrade 005 without discarding reservations or changing existing ownership.
BEGIN;
ALTER TABLE reservations DROP CONSTRAINT reservations_status_check;
ALTER TABLE reservations
    ADD COLUMN expires_at TIMESTAMP WITH TIME ZONE,
    ADD COLUMN payment_reference VARCHAR(128) UNIQUE,
    ADD CONSTRAINT reservations_status_check
        CHECK (status IN ('ACTIVE', 'CONFIRMED', 'CANCELLED', 'EXPIRED', 'REFUND_PENDING', 'REFUNDED')),
    ADD CONSTRAINT reservations_deadline_after_creation CHECK (expires_at IS NULL OR expires_at > created_at),
    ADD CONSTRAINT reservations_payment_state_check CHECK (
        (status IN ('CONFIRMED', 'REFUND_PENDING', 'REFUNDED') AND payment_reference IS NOT NULL)
        OR (status IN ('ACTIVE', 'CANCELLED', 'EXPIRED') AND payment_reference IS NULL)
    );

-- Anonymous rows preserved by 005 remain inaccessible and unchanged. New rows still require an owner.
UPDATE reservations r
SET expires_at = GREATEST(r.created_at + INTERVAL '1 microsecond',
                         LEAST(e.starts_at, CURRENT_TIMESTAMP + INTERVAL '15 minutes'))
FROM events e WHERE e.id = r.event_id AND r.status = 'ACTIVE' AND r.user_id IS NOT NULL;
ALTER TABLE reservations ADD CONSTRAINT reservations_hold_deadline_check
    CHECK (status <> 'ACTIVE' OR user_id IS NULL OR expires_at IS NOT NULL);

-- Refuse an inconsistent upgrade rather than silently giving occupied seats to a second reservation.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM events e
        LEFT JOIN (SELECT event_id, SUM(quantity) AS occupied FROM reservations WHERE status='ACTIVE' GROUP BY event_id) r
            ON r.event_id=e.id
        WHERE e.capacity - e.available_seats <> COALESCE(r.occupied, 0)
    ) THEN
        RAISE EXCEPTION 'Reservation inventory is inconsistent; reconcile it before applying migration 006';
    END IF;
END $$;

CREATE TABLE event_seats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    seat_number INTEGER NOT NULL CHECK (seat_number > 0),
    reservation_id UUID REFERENCES reservations(id) ON DELETE SET NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT event_seats_event_number_unique UNIQUE (event_id, seat_number)
);
CREATE INDEX idx_event_seats_reservation ON event_seats(reservation_id);

CREATE TABLE reservation_seats (
    reservation_id UUID NOT NULL REFERENCES reservations(id) ON DELETE CASCADE,
    seat_position INTEGER NOT NULL CHECK (seat_position >= 0),
    seat_number INTEGER NOT NULL CHECK (seat_number > 0),
    PRIMARY KEY (reservation_id, seat_position),
    UNIQUE (reservation_id, seat_number)
);

INSERT INTO event_seats (event_id, seat_number)
SELECT e.id, number FROM events e CROSS JOIN LATERAL generate_series(1, e.capacity) AS number;

-- Previously unnumbered ACTIVE reservations get deterministic, disjoint seat ranges.
WITH ranges AS (
    SELECT id, event_id, quantity,
           COALESCE(SUM(quantity) OVER (PARTITION BY event_id ORDER BY created_at, id
               ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING), 0)::integer AS seat_offset
    FROM reservations WHERE status='ACTIVE'
), allocation AS (
    SELECT r.id, r.event_id, r.seat_offset + n AS seat_number
    FROM ranges r CROSS JOIN LATERAL generate_series(1, r.quantity) AS n
)
UPDATE event_seats s SET reservation_id=a.id FROM allocation a
WHERE s.event_id=a.event_id AND s.seat_number=a.seat_number;

INSERT INTO reservation_seats (reservation_id, seat_position, seat_number)
SELECT reservation_id, (ROW_NUMBER() OVER (PARTITION BY reservation_id ORDER BY seat_number) - 1)::integer, seat_number
FROM event_seats WHERE reservation_id IS NOT NULL;

CREATE INDEX idx_reservations_due ON reservations(expires_at, id) WHERE status='ACTIVE' AND expires_at IS NOT NULL;
CREATE INDEX idx_reservations_owner_page ON reservations(user_id, created_at DESC, id DESC);
COMMIT;
